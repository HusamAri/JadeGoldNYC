def hero(p):
    comp = {
        # the station is the product at thumbnail size (L12): the chain leaves the frame, the clasp is
        # not shown, so the decorated part is large enough to read at 250 px
        "bracelet": ("The decorated centre of the bracelet lies face up at the centre of the honed grey "
                     "stone slab, close to the camera; the chain runs away from it on both sides in a soft "
                     "curve and leaves the frame at the left and right edges; the clasp is out of frame."),
        "necklace": ("The pendant lies flat and face up on the honed grey stone slab, the chain running in a "
                     "soft loose curve up and out of the top edge of the frame."),
        "earrings": ("The pair lies side by side on the honed grey stone slab, both fronts facing the camera, "
                     "about 15 mm apart, posts hidden underneath; exactly two earrings."),
        "brooch": ("The brooch lies face up, centred on the honed grey stone slab, pin hidden behind it; "
                   "exactly one brooch."),
    }[p["category"]]
    fill = ("the decorated part in razor-sharp focus, filling about a third of the frame width, with the "
            "chain softly out of focus toward the frame edges"
            if p["category"] in ("bracelet", "necklace") else
            "the piece in razor-sharp focus, filling about 45 percent of the frame width, centred with "
            "generous empty margin on all four sides")
    return anchor(f"{HERO_STYLE} The piece: {p['camera']} {truth(p)} {comp} Seen from about 30 degrees "
                  f"above with a 100 mm macro lens, {fill}. No people and no hands.")


def gallery(p, scene):
    return anchor(f"{GALLERY_STYLE} {reference(p)} The piece: {p['camera']} {truth(p)} {scene}")


def alt(p, code):
    base = p["alt_base"]
    return {
        "01": base,
        "02": f"{base}, worn",
        "03": f"Close-up of {p['alt_macro']}",
        "04": f"{base}, held between fingers for scale",
        "05": f"Back of the {p['noun']} showing {p['alt_back']}",
        "06": f"{base}, {'full length' if p['category'] in ('bracelet', 'necklace') else 'pair' if p['category'] == 'earrings' else 'pin open'}",
        "07": f"Side profile of the {p['noun']} showing its thickness",
        "08": f"{base}, styled with winter knitwear",
        "09": f"{base} in a gift box",
        "10": f"{base} in neutral daylight, true colour",
        "11": f"{base} with space for dimensions",
        "12": f"{base} on a jeweller's bench",
        "13": f"{base} on a deep green card",
        "14": f"{base}, everyday wear",
        "15": f"{base} given as a gift",
        "16": f"{base}, flat lay on deep green",
    }[code]


out, jobs = {}, []
for i, p in enumerate(CAT["products"]):
    for f in ("camera", "macro", "back", "side"):
        assert not SIMILE.search(p[f]), (p["id"], f, SIMILE.search(p[f]).group(0))
    if not p["stones"]:
        for f in ("camera", "macro", "back", "side"):
            assert not STONE_WORD.search(p[f]), (p["id"], f, "stone word on a stoneless piece")
    if not p["enamel"]:
        for f in ("camera", "macro", "back", "side", "bench_props"):
            assert "enamel" not in p[f].lower(), (p["id"], f, "enamel word on an enamel-free piece")
    if re.search(r"\bstars?\b", p["camera"], re.I):
        assert STAR_COUNT.search(p["camera"]), (p["id"], "star without a point count")
    items = [{"code": "01", "purpose": "Hero / arama küçük resmi: tek ürün, marka natürmortu, 4:3.",
              "reference": False, "prompt": hero(p), "alt": alt(p, "01")}]
    for code, purpose, ref, scene in frames(p):
        items.append({"code": code, "purpose": purpose, "reference": ref,
                      "prompt": gallery(p, scene), "alt": alt(p, code)})
    for it in items:
        assert len(it["alt"]) <= 250, (p["id"], it["code"])
        if it["reference"]:
            assert "attached reference" in it["prompt"]
        else:
            assert "reference" not in it["prompt"].lower(), (p["id"], "hero must not name a reference")
    out[p["id"]] = items
    jobs.append({"id": p["id"], "frame": "01", **JOB, "seed": 2026_1200 + i, "prompt": items[0]["prompt"]})

assert sum(len(v) for v in out.values()) == 16 * len(CAT["products"])
json.dump(out, open(HERE / "prompts.json", "w"), ensure_ascii=False, indent=1)
(HERE / "images").mkdir(exist_ok=True)
json.dump({"why_explicit": "resolution defaults to 1k on this model; 2k must be passed on every call",
           "params": JOB, "jobs": jobs}, open(HERE / "images" / "jobs.json", "w"), ensure_ascii=False, indent=1)
print(f"{len(out)} products, {sum(len(v) for v in out.values())} prompts")
