"""Jade Gold NYC, Christmas 2026: 16 image prompts for each of the 40 pieces (640 in all).

Run: python3 -I docs/jade/xmas26/prompts.py  -> prompts.json + images/jobs.json
Nothing here calls a model. Frame 01 is the hero (generated in this repo, no reference image);
frames 02-16 are generated by the owner WITH a tight crop of that product's hero attached as the
only reference (images/heroes/crops/<ID>.jpg).

Every prompt is ONE generation with the parameters pinned in JOB below. `resolution` is passed
explicitly because the model defaults to 1k (second-brain 2026-10-13: five heroes lost to it).

The piece is described by catalog.json's `camera` text and nothing else, so the picture and the
listing cannot drift apart. That text is camera nouns only: no simile, no sales voice
(second-brain 2026-10-16: "like a string of lights" put fairy lights in the frame). Guards at the
bottom assert it.

Every scene sentence below has to be true in the category it lands in. A sentence that does not
fit gets made true by the model adding an object (second-brain 2026-09-30: a "resting on the
table" clause put a second pair of earrings on the table), so scene text is chosen per category.
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).parent
CAT = json.load(open(HERE / "catalog.json"))

JOB = {
    "model": "nano_banana_2_1",
    "aspect_ratio": "4:3",
    "resolution": "2k",  # MUST be explicit: default is 1k
    "thinking_level": "high",
    "count": 1,
}

# The brand's own words (public/brand/jade-gold-nyc-guidelines.html: Antique Gold, Warm Ivory,
# Stone Grey, Deep Jade; "Modern Heirlooms"). Hero only: it describes a set, not a person.
HERO_STYLE = (
    "Quiet luxury editorial still-life product photography. Warm ivory linen ground, honed grey "
    "stone slab, a sliver of deep jade-green matte card. Soft directional window light from upper "
    "left, long soft shadow, shallow depth of field. Solid yellow gold with warm antique tone. "
    "Restrained heirloom mood. No text, no logo, no glitter, no Christmas decoration."
)
# Shared by frames 02-16. True on every frame: it names colour and light, never a set.
GALLERY_STYLE = (
    "Quiet luxury editorial photography in warm ivory, stone grey and deep jade-green tones, soft "
    "directional window light from the upper left, true colour, fine film grain, no heavy "
    "retouching. No text, no logo, no watermark, no glitter."
)


def reference(p):
    """Names only what this piece has: "keep its stones" on a stoneless piece invites stones."""
    keep = ["shape", "proportions", "gold colour"]
    if p["enamel"]:
        keep.append("enamel colours")
    if p["stones"]:
        keep.append("stones")
    return ("The attached reference image is a crop of this exact piece: keep its "
            f"{', '.join(keep[:-1])} and {keep[-1]} exactly as in the reference.")

HANDS = "anatomically correct hands with five fingers, short natural unpolished nails"
# Colour names drift in the model (deep berry -> bright red, jade -> emerald, ice-blue -> royal
# blue; verifier finding 2026-10-18). The first mention of each enamel colour in a prompt carries
# one fixed plain-language anchor, the same words on all 640 prompts.
COLOUR_ANCHORS = {
    "ice-blue enamel": "ice-blue enamel (a soft pale powder blue with a grey cast)",
    "jade-green enamel": "jade-green enamel (a dark muted grey-green)",
    "berry enamel": "berry enamel (a dark wine red, not bright red)",
    "navy-blue enamel": "navy-blue enamel (a deep dark blue)",
}


def anchor(text):
    for k, v in COLOUR_ANCHORS.items():
        text = re.sub(re.escape(k), v, text, count=1)
    return text


SIMILE = re.compile(r"\b(like|as if|as though|resembl\w*|reminiscent)\b", re.I)
STONE_WORD = re.compile(r"\b(stone|stones|sapphire|sapphires|diamond(?![- ]cut)|diamonds|gem|gems|gemstone)\b", re.I)  # "diamond-cut" is a finish
STAR_COUNT = re.compile(r"\b(\d+|four|five|six|seven|eight|ten|twelve)[- ]point(ed)?\b", re.I)


def truth(p):
    """What the piece carries, stated positively and exactly. A stoneless piece says so in full,
    because "no stones" next to a style word about sparkle has been read as stones before
    (Stellar N01, 2026-10-15)."""
    parts = []
    if p["stones"]:
        parts.append(f"The stones are exactly these and no others: {p['stone_phrase']}. "
                     "No other stone and no empty setting anywhere on the piece.")
    else:
        parts.append("The piece carries no gemstones at all and no empty settings.")
    if p["enamel"]:
        parts.append(f"The only colour on the piece is {p['enamel_phrase']}; every other surface is "
                     "yellow gold.")
    else:
        parts.append("The piece has no enamel and no colour: every surface is yellow gold.")
    return " ".join(parts)


def size_line(p):
    mm = p["max_mm"]
    return f"true to scale, the main element measures about {mm:g} mm across"


def worn(p):
    c = p["category"]
    if c == "bracelet":
        return ("Worn on a woman's left wrist, the forearm resting on a folded warm-ivory wool knit, "
                "hand relaxed and open; the stations sit face up on the top of the wrist; it is the only "
                f"jewellery in the image, no watch and no rings; {size_line(p)}; {HANDS}.")
    if c == "necklace":
        return ("Worn by a woman against bare skin just below the collarbone, above the open neckline of "
                "a warm-ivory silk blouse, cropped from chin to mid-chest so no face shows; the pendant "
                f"hangs centred and faces the camera; it is the only jewellery in the image; {size_line(p)}.")
    if c == "earrings":
        return ("One earring worn on a woman's left earlobe, side profile, hair tucked behind the ear, "
                "cropped tight from cheekbone to jaw; only one ear is in the frame and exactly one earring "
                f"is visible; no other earrings and no piercings elsewhere; {size_line(p)}.")
    if p["wearer"] == "men":
        return ("Pinned through the left lapel of a man's charcoal grey wool flannel suit jacket at the "
                "buttonhole, white shirt, no tie, cropped from collar to chest so no face shows; exactly "
                f"one pin on the jacket and no pocket square; {size_line(p)}.")
    return ("Pinned on the left lapel of a woman's camel wool coat, cropped from collar to chest so no "
            f"face shows; exactly one brooch on the coat and no other jewellery; {size_line(p)}.")


def held(p):
    c = p["category"]
    if c == "bracelet":
        pose = ("the bracelet held up between the thumb and index finger of a woman's hand by its clasp, "
                "the chain hanging straight down so every station faces the camera")
    elif c == "necklace":
        pose = ("the pendant resting on the fingertips of a woman's open hand, face up, the chain running "
                "out of the frame")
    elif c == "earrings":
        pose = ("one earring held between the thumb and index finger of a woman's hand by its edges, front "
                "facing the camera; the second earring is not in the frame")
    else:
        pose = "the brooch resting face up on the open palm of a woman's hand"
    return (f"Close-up for scale against a plain warm-ivory background thrown softly out of focus: {pose}; "
            f"{size_line(p)}, a fingertip is about 16 mm wide; it is the only jewellery in the image; {HANDS}.")


def full(p):
    c = p["category"]
    if c == "bracelet":
        return ("The whole bracelet laid out in one straight horizontal line on warm-ivory linen, top-down, "
                "from the lobster clasp at one end to the extender chain at the other, every station face up "
                "and the extender rings visible.")
    if c == "necklace":
        return ("The whole necklace laid out top-down on warm-ivory linen in a straight vertical line, chain "
                "doubled into a narrow U, pendant face up at the bottom, lobster clasp and extender chain at "
                "the top.")
    if c == "earrings":
        return ("The pair laid flat side by side on warm-ivory linen, top-down, both fronts to the camera, "
                "mirror-symmetric, about 15 mm apart, exactly two earrings.")
    return ("The brooch lying face down on honed grey stone with its pin stem swung open out of the safety "
            "catch so the full length of the pin, the hinge joint and the open catch are all visible, "
            "top-down.")


def gift(p):
    c = p["category"]
    what = {"bracelet": "the bracelet coiled loosely", "necklace": "the pendant face up, chain coiled",
            "earrings": "the pair side by side, fronts up", "brooch": "the brooch face up"}[c]
    return (f"Top-down: {what} inside a small open square gift box in plain warm-ivory card with a soft "
            "ivory insert, the lid set beside it, a length of narrow deep jade-green ribbon untied beside "
            "the box, on honed grey stone. No branding, no printed pattern, no tissue paper, no Christmas "
            "decoration, exactly one box.")


def life(p):
    c = p["category"]
    if c == "bracelet":
        return ("Morning window light: a woman's left wrist wearing the bracelet rests on the cuff of an ivory "
                "cable-knit sweater beside a small stoneware cup of black coffee on a pale oak table; it is the "
                f"only jewellery in the image; {HANDS}.")
    if c == "necklace":
        return ("Winter afternoon light: a woman wearing the necklace over a fine ivory cashmere crew-neck "
                "sweater, cropped from chin to chest, a grey wool coat collar at the edge of the frame; it is "
                "the only jewellery in the image.")
    if c == "earrings":
        return ("Winter afternoon light: three-quarter view of a woman with dark hair pulled back into a low "
                "knot, ivory turtleneck sweater, cropped below the eyes; exactly one earring visible on the "
                "near ear; it is the only jewellery in the image.")
    if p["wearer"] == "men":
        return ("Outdoors in pale winter light: a man in a navy wool overcoat with the pin through the left "
                "lapel, a grey scarf, cropped from collar to chest so no face shows; exactly one pin.")
    return ("Outdoors in pale winter light: a woman in an ivory wool coat with the brooch on the left lapel, "
            "a grey knit scarf, cropped from collar to chest so no face shows; exactly one brooch.")


def everyday(p):
    c = p["category"]
    if c == "bracelet":
        return ("Everyday wear, no season: a woman's left wrist wearing the bracelet over a laptop keyboard "
                f"in soft daylight, plain white cotton shirt cuff; only jewellery in the image; {HANDS}.")
    if c == "necklace":
        return ("Everyday wear, no season: a woman wearing the necklace with a plain white cotton shirt open "
                "at the collar, soft daylight, cropped from chin to chest; the only jewellery in the image.")
    if c == "earrings":
        return ("Everyday wear, no season: side profile of a woman with short dark hair, plain white t-shirt "
                "collar, soft daylight, cropped from cheekbone to jaw; exactly one earring visible on the "
                "near ear.")
    if p["wearer"] == "men":
        return ("Everyday wear, no season: the pin on the lapel of a man's unstructured stone-grey linen "
                "blazer over a white t-shirt, soft daylight, cropped from collar to chest; exactly one pin.")
    return ("Everyday wear, no season: the brooch on the collar of a woman's ivory denim jacket, soft "
            "daylight, cropped from collar to chest; exactly one brooch.")


def giving(p):
    return ("A gift being given: two pairs of hands across a pale oak table, one pair holding out the small "
            "open warm-ivory gift box with the piece visible inside, the other reaching for it, soft warm "
            "window light, sleeves of ivory and grey knitwear; exactly one box and one piece of jewellery; "
            f"{HANDS}.")


